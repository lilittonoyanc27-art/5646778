export function normalizeAnswer(str: string): string {
  return str
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, (match) => {
      // Retain 'ñ' behavior if desired, but also allow 'n' for convenience
      return match;
    })
    .replace(/[.,/#!$%^&*;:{}=\-_`~()?'"¡¿]/g, '')
    .replace(/\s+/g, ' ');
}

export function isAnswerCorrect(userInput: string, question: QuestionItem): boolean {
  const normalizedInput = normalizeAnswer(userInput);
  if (!normalizedInput) return false;

  const validOptions = [
    question.answerES,
    ...question.acceptedAnswers
  ].map(normalizeAnswer);

  // Exact match or matches any accepted spelling
  if (validOptions.includes(normalizedInput)) return true;

  // Also check without accent marks (e.g., 'kilometro' matches 'kilómetro', 'nino' matches 'niño')
  const stripAccents = (s: string) =>
    s
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase();

  const strippedInput = stripAccents(normalizedInput);
  return validOptions.some((opt) => stripAccents(opt) === strippedInput);
}
